/**
 * El comando del botón: pide la medición de la imagen del cuadro activo y la
 * deja como dos ángulos Cobb editables. Ver `medicion.ts` para la geometría y
 * `toth/ia-caderas.mjs` para el lado del servidor.
 */

import { getEnabledElementByViewportId, metaData, utilities as csUtils } from '@cornerstonejs/core';
import {
  AngleTool,
  CobbAngleTool,
  LengthTool,
  annotation as csAnnotation,
} from '@cornerstonejs/tools';
import { wadouri } from '@cornerstonejs/dicom-image-loader';

import { seguirAngulo } from './correcciones';
import { compartirHilgenreiner } from './hilgenreiner';
import {
  PREFIJO,
  angulosCaderas,
  avisoDeError,
  caderaDeLaIzquierda,
  cobbCaderas,
  etiqueta,
  textosCaderas,
  urlMedicion,
  type Mitad,
  type Punto,
} from './medicion';

const TITULO = 'Medir IA';

/** PatientOrientation del archivo ya bajado (el manifiesto no la trae), como hace toth-overlay. */
export function orientacion(imageId: string): string | undefined {
  try {
    const { url } = wadouri.parseImageId(imageId);
    const dataSet = wadouri.dataSetCacheManager.get(url);
    return dataSet?.string?.('x00200020');
  } catch {
    return undefined;
  }
}

// Las caderas son Cobb; la pierna, y las caderas medidas antes de noviembre de 2026, Ángulo; los largos y
// desniveles de la pierna, Longitud.
const HERRAMIENTAS_IA = [AngleTool.toolName, CobbAngleTool.toolName, LengthTool.toolName];

/** Las mediciones anteriores de la IA sobre esta imagen: volver a apretar el botón las reemplaza. */
export function borrarAnteriores(imageId: string, prefijos: string[] = [PREFIJO]) {
  for (const a of csAnnotation.state.getAllAnnotations()) {
    const label = String(a.data?.label ?? '');
    if (
      HERRAMIENTAS_IA.includes(a.metadata?.toolName) &&
      a.metadata?.referencedImageId === imageId &&
      prefijos.some(p => label.startsWith(p))
    ) {
      csAnnotation.state.removeAnnotation(a.annotationUID);
    }
  }
}

/**
 * Lo mismo que hace AngleTool.hydrate, pero con la etiqueta puesta antes de
 * agregarla: OHIF crea la medición al oír ANNOTATION_ADDED y la toma de ahí.
 * `extra` va a `data` (la pierna guarda ahí qué mide, para su texto).
 * `herramienta`: Ángulo con tres puntos (la pierna), Cobb con cuatro (las
 * caderas) o Longitud con dos (los largos y desniveles de la pierna).
 * `texto`: dónde va el recuadro del valor, en el mundo, si no se deja donde lo
 * pone la herramienta; queda ahí aunque se muevan los puntos, como si el
 * radiólogo lo hubiera arrastrado.
 */
export function agregarAngulo(
  viewportId: string,
  imageId: string,
  puntos: number[][],
  label: string,
  extra: Record<string, unknown> = {},
  {
    herramienta = AngleTool,
    texto,
  }: {
    herramienta?: typeof AngleTool | typeof CobbAngleTool | typeof LengthTool;
    texto?: number[];
  } = {}
): string {
  const enabledElement = getEnabledElementByViewportId(viewportId);
  const { FrameOfReferenceUID, referencedImageId, viewPlaneNormal, viewport } = (
    herramienta as unknown as { hydrateBase: (...args: unknown[]) => any }
  ).hydrateBase(herramienta, enabledElement, puntos, { referencedImageId: imageId });

  const annotationUID = csUtils.uuidv4();
  csAnnotation.state.addAnnotation(
    {
      annotationUID,
      data: {
        handles: {
          points: puntos,
          activeHandleIndex: null,
          ...(texto && {
            textBox: {
              hasMoved: true,
              worldPosition: texto,
              // Lo recalcula cada dibujo; así viene de la herramienta antes del primero.
              worldBoundingBox: {
                topLeft: [0, 0, 0],
                topRight: [0, 0, 0],
                bottomLeft: [0, 0, 0],
                bottomRight: [0, 0, 0],
              },
            },
          }),
        },
        label,
        cachedStats: {},
        ...extra,
      },
      highlighted: false,
      autoGenerated: false,
      invalidated: true,
      isLocked: false,
      isVisible: true,
      metadata: {
        toolName: herramienta.toolName,
        viewPlaneNormal,
        FrameOfReferenceUID,
        referencedImageId,
      },
    } as any,
    viewport.element
  );
  return annotationUID;
}

export async function medirIndiceAcetabular({ servicesManager }) {
  const { viewportGridService, cornerstoneViewportService, uiNotificationService } =
    servicesManager.services;
  const avisar = (type: 'info' | 'success' | 'warning' | 'error', message: string) =>
    uiNotificationService.show({
      title: TITULO,
      message,
      type,
      duration: type === 'error' ? 6000 : 4000,
    });

  const viewportId = viewportGridService.getActiveViewportId();
  const viewport = cornerstoneViewportService.getCornerstoneViewport(viewportId);
  const imageId: string | undefined = viewport?.getCurrentImageId?.();
  if (!imageId) {
    avisar('warning', 'Abre una RX de pelvis en el cuadro activo.');
    return;
  }

  const url = urlMedicion(imageId, metaData.get('instance', imageId));
  if (!url) {
    avisar('warning', 'Esta imagen no viene del archivo del centro: no se puede medir.');
    return;
  }

  let respuesta: Response;
  let cuerpo;
  try {
    respuesta = await fetch(url, { credentials: 'same-origin' });
    cuerpo = await respuesta.json().catch(() => null);
  } catch {
    avisar('error', 'No se pudo contactar al servicio de IA.');
    return;
  }
  if (!respuesta.ok || !cuerpo?.ok) {
    avisar(respuesta.status === 422 ? 'warning' : 'error', avisoDeError(respuesta.status, cuerpo));
    return;
  }

  // Sobre la imagen que se midió, aunque el cuadro haya avanzado mientras tanto.
  borrarAnteriores(imageId);
  const izquierda = caderaDeLaIzquierda(orientacion(imageId));
  const cadera: Record<Mitad, 'derecha' | 'izquierda'> = {
    izq: izquierda,
    der: izquierda === 'derecha' ? 'izquierda' : 'derecha',
  };
  // El servicio da el centro del primer píxel como (0, 0); Cornerstone, su esquina.
  const aMundo = ([x, y]: Punto) => csUtils.imageToWorldCoords(imageId, [x + 0.5, y + 0.5]);
  const angulos = angulosCaderas(cuerpo.puntos);
  const cobb = cobbCaderas(cuerpo.puntos);
  const textos = textosCaderas(cuerpo.puntos);
  const uids = {} as Record<Mitad, string>;
  for (const mitad of ['izq', 'der'] as const) {
    const uid = agregarAngulo(
      viewportId,
      imageId,
      cobb[mitad].map(aMundo),
      etiqueta(cadera[mitad]),
      {},
      { herramienta: CobbAngleTool, texto: aMundo(textos[mitad]) }
    );
    uids[mitad] = uid;
    seguirAngulo(uid, {
      url,
      imageId,
      campos: { cadera: cadera[mitad], mitad },
      modelo: String(cuerpo.modelo ?? ''),
      puntosIa: angulos[mitad],
    });
  }
  compartirHilgenreiner(uids.izq, uids.der, viewportId);
  viewport.render();
  avisar(
    'success',
    'Ángulos listos: revísalos y mueve los puntos si hace falta. Las correcciones se guardan para entrenar la IA.'
  );
}
